const modalLista =
    document.getElementById("modalLista");

const lista =
    document.getElementById("lista");


function construirLista() {

    lista.innerHTML = "";

    for (let i = 1; i <= 50; i++) {

        const elemento =
            document.createElement("div");

        elemento.classList.add(
            "lista-item"
        );

        elemento.textContent =
            i;

        if (i < nivelActual) {

            elemento.classList.add(
                "completada"
            );

        }

        if (i === nivelActual) {

            elemento.classList.add(
                "actual"
            );

        }

        lista.appendChild(elemento);

    }

}


document
    .getElementById("listaPreguntas")
    .addEventListener(
        "click",
        function () {

            construirLista();

            modalLista.classList.add(
                "activo"
            );

        }
    );


document
    .getElementById("cerrarLista")
    .addEventListener(
        "click",
        function () {

            modalLista.classList.remove(
                "activo"
            );

        }
    );


