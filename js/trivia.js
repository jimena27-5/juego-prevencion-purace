// =====================================================
// MOSTRAR VIDAS
// =====================================================

function actualizarVidas() {

    let corazones = "";

    for (let i = 0; i < 3; i++) {

        if (i < vidas) {
            corazones += "❤️";
        } else {
            corazones += "🖤";
        }

    }

    vidasTexto.textContent = corazones;
}


// =====================================================
// MOSTRAR PREGUNTA
// =====================================================

function mostrarPregunta() {

    respondida = false;

    const datos =
        preguntas[nivelActual - 1];

    nivelTexto.textContent =
        nivelActual + " / 50";

    numeroPregunta.textContent =
        nivelActual;

    preguntaTexto.textContent =
        datos.pregunta;

    document.getElementById("textoA").textContent =
        datos.A;

    document.getElementById("textoB").textContent =
        datos.B;

    document.getElementById("textoC").textContent =
        datos.C;

    document.getElementById("textoD").textContent =
        datos.D;


    botonesRespuesta.forEach(boton => {

        boton.disabled = false;

        boton.classList.remove(
            "correcta",
            "incorrecta"
        );

    });


    mensaje.textContent = "";

    mensaje.className = "mensaje";

    siguiente.classList.remove("visible");


    const porcentaje =
        (nivelActual / 50) * 100;

    progreso.style.width =
        porcentaje + "%";

    progresoTexto.textContent =
        nivelActual + " / 50";

    actualizarVidas();

    actualizarMonedas();

}


// =====================================================
// RESPONDER
// =====================================================

function responder(opcion) {

    if (respondida) {
        return;
    }

    respondida = true;

    const datos =
        preguntas[nivelActual - 1];

    botonesRespuesta.forEach(boton => {

        boton.disabled = true;

    });


    const botonElegido =
        document.querySelector(
            `.respuesta[data-opcion="${opcion}"]`
        );


    const botonCorrecto =
        document.querySelector(
            `.respuesta[data-opcion="${datos.correcta}"]`
        );


    if (opcion === datos.correcta) {

        botonElegido.classList.add("correcta");

        mensaje.textContent =
            "✅ ¡CORRECTO!";

        mensaje.classList.add("correcto");

        puntaje += 10;

        siguiente.classList.add("visible");

    } else {

        botonElegido.classList.add("incorrecta");

        botonCorrecto.classList.add("correcta");

        mensaje.textContent =
            "❌ INCORRECTO — La respuesta correcta era " +
            datos.correcta;

        mensaje.classList.add("incorrecto");

        vidas--;

        actualizarVidas();

        siguiente.classList.add("visible");

        if (vidas <= 0) {

            setTimeout(() => {

                mostrarDerrota();

            }, 900);

        }

    }

}


