// =====================================================
// VOZ
// =====================================================

function hablarPregunta() {

    if (!("speechSynthesis" in window)) {
        return;
    }

    window.speechSynthesis.cancel();

    const datos =
        preguntas[nivelActual - 1];

    const texto =

        "Pregunta número " +
        nivelActual +
        ". " +
        datos.pregunta +
        ". " +

        "Respuesta A: " +
        datos.A +
        ". " +

        "Respuesta B: " +
        datos.B +
        ". " +

        "Respuesta C: " +
        datos.C +
        ". " +

        "Respuesta D: " +
        datos.D;


    const voz =
        new SpeechSynthesisUtterance(texto);

    voz.lang = "es-CO";

    voz.rate = 0.9;

    voz.pitch = 1;

    window.speechSynthesis.speak(voz);

}


